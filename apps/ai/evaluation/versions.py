"""Pin the model, prompt, retrieval and output contract to one evaluated revision."""

from __future__ import annotations

from hashlib import sha256
from pathlib import Path
from typing import TYPE_CHECKING

import rfc8785

from apps.ai.contracts import Purpose
from apps.ai.prompt_registry import load_prompt

if TYPE_CHECKING:
    from apps.ai.models import ModelConfiguration

ROOT = Path(__file__).resolve().parents[3]


def _source_hash(paths: tuple[str, ...]) -> str:
    digest = sha256()
    for name in paths:
        content = (ROOT / name).read_bytes()
        digest.update(name.encode() + b"\0" + len(content).to_bytes(8) + content)
    return digest.hexdigest()


def governed_paths() -> tuple[str, ...]:
    """Fingerprint the whole application boundary, including future dependencies.

    A purpose-specific import allowlist missed validators added by later todos.
    Conservative shared invalidation is intentional: a new import, dynamic
    dispatch, domain bridge, fixture or pinned dependency cannot escape review.
    Evidence, runtime data, generated bytecode and the test tree are excluded.
    """
    return tuple(
        sorted(
            {
                path.relative_to(ROOT).as_posix()
                for directory in ("apps", "config", "docs/ai")
                for path in (ROOT / directory).rglob("*")
                if path.is_file() and path.suffix in {".py", ".json", ".md", ".sql"}
            }
            | {
                "uv.lock",
                "pyproject.toml",
                "locale/pt_BR/LC_MESSAGES/django.po",
                "locale/pt_BR/LC_MESSAGES/django.mo",
            }
        )
    )


def source_versions(purpose: Purpose) -> dict[str, str]:
    """Invalidate old approval whenever an admitted source contract changes."""
    identity = _source_hash(governed_paths())
    return {
        "prompt": load_prompt(purpose)[1],
        "retrieval": identity,
        "schema": identity,
    }


def candidate_versions(configuration: ModelConfiguration) -> dict[str, str | int]:
    """Include price, jurisdiction and version identity in the immutable digest."""
    terms = {
        name: getattr(configuration, name)
        for name in (
            "purpose",
            "provider",
            "model_id",
            "region",
            "jurisdiction_class",
            "endpoint",
            "retention_terms",
            "training_terms",
            "input_micros",
            "output_micros",
            "cached_micros",
            "audio_micros",
            "version",
            "route",
            "timeout_seconds",
        )
    }
    return {
        "model": sha256(rfc8785.dumps(terms)).hexdigest(),
        "version": configuration.version,
        **source_versions(Purpose(configuration.purpose)),
    }

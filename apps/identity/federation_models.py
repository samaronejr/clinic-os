"""Retained enterprise directory authority, separate from clinical identifiers."""

from __future__ import annotations

import uuid
from typing import ClassVar

from django.conf import settings
from django.db import models

from apps.tenancy.fields import EncryptedJSONField
from apps.tenancy.models import TenantScopedModel


class SsoConnection(TenantScopedModel):
    """An immutable, organization-wide OIDC configuration version."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    clinic = models.ForeignKey("identity.Clinic", on_delete=models.PROTECT)
    configuration = EncryptedJSONField(purpose="identity.sso.configuration")
    # Provider registry surrogates are regenerated by logical recovery.
    # Bind the logical capability, never a non-restored platform UUID.
    provider_key = models.CharField(max_length=64, default="enterprise_identity")
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT)
    created_at = models.DateTimeField(auto_now_add=True)
    revoked_at = models.DateTimeField(null=True)

    class Meta:
        """Only one current federation connection governs an organization."""

        constraints: ClassVar = [
            models.UniqueConstraint(
                fields=("organization",),
                condition=models.Q(revoked_at__isnull=True),
                name="identity_sso_one_current",
            ),
        ]


class ScimToken(TenantScopedModel):
    """A high-entropy, hash-only, expiring directory capability."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    clinic = models.ForeignKey("identity.Clinic", on_delete=models.PROTECT)
    connection = models.ForeignKey(
        SsoConnection, on_delete=models.PROTECT, related_name="tokens"
    )
    secret_hash = models.BinaryField(unique=True)
    issued_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT)
    created_at = models.DateTimeField(auto_now_add=True)
    expires_at = models.DateTimeField()
    revoked_at = models.DateTimeField(null=True)
    window_start = models.DateTimeField()
    window_count = models.PositiveIntegerField(default=0)


class ScimResource(TenantScopedModel):
    """Opaque SCIM id; attributes are encrypted, never URL or audit content."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    clinic = models.ForeignKey("identity.Clinic", on_delete=models.PROTECT)
    connection = models.ForeignKey(SsoConnection, on_delete=models.PROTECT)
    kind = models.CharField(max_length=6)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.PROTECT, related_name="+"
    )
    external_hash = models.BinaryField(null=True)
    search_hash = models.BinaryField(db_index=True)
    attributes = EncryptedJSONField(purpose="identity.scim.attributes")
    active = models.BooleanField(default=True)
    revision = models.PositiveIntegerField(default=1)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    deleted_at = models.DateTimeField(null=True)

    class Meta:
        """A client subject cannot be rebound to a different local account."""

        constraints: ClassVar = [
            models.CheckConstraint(
                condition=models.Q(kind="Users", user__isnull=False)
                | models.Q(kind="Groups", user__isnull=True),
                name="identity_scim_resource_shape",
            ),
            models.UniqueConstraint(
                fields=("connection", "kind", "external_hash"),
                name="identity_scim_external_unique",
            ),
            models.UniqueConstraint(
                fields=("connection", "search_hash"),
                condition=models.Q(kind="Users", deleted_at__isnull=True),
                name="identity_scim_username_current",
            ),
        ]


class ScimRoleMapping(TenantScopedModel):
    """Only a verified organization admin approves a group-to-unit role."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    clinic = models.ForeignKey("identity.Clinic", on_delete=models.PROTECT)
    group = models.ForeignKey(ScimResource, on_delete=models.PROTECT)
    unit = models.ForeignKey(
        "identity.Clinic", on_delete=models.PROTECT, related_name="+"
    )
    bundle = models.CharField(max_length=20)
    approved_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT)
    created_at = models.DateTimeField(auto_now_add=True)
    revoked_at = models.DateTimeField(null=True)

    class Meta:
        """Keep current mappings unique while retaining revoked history."""

        constraints: ClassVar = [
            models.UniqueConstraint(
                fields=("group", "unit", "bundle"),
                condition=models.Q(revoked_at__isnull=True),
                name="identity_scim_mapping_current",
            ),
        ]


class ScimMembership(TenantScopedModel):
    """Retained directory group membership, not a staff role in itself."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    clinic = models.ForeignKey("identity.Clinic", on_delete=models.PROTECT)
    group = models.ForeignKey(ScimResource, on_delete=models.PROTECT, related_name="+")
    member = models.ForeignKey(ScimResource, on_delete=models.PROTECT, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)
    revoked_at = models.DateTimeField(null=True)

    class Meta:
        """A removed member can later acquire a new, separately audited binding."""

        constraints: ClassVar = [
            models.UniqueConstraint(
                fields=("group", "member"),
                condition=models.Q(revoked_at__isnull=True),
                name="identity_scim_member_current",
            ),
        ]


class ScimRoleBinding(TenantScopedModel):
    """Distinguish managed memberships from independently owner-issued bundles."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    clinic = models.ForeignKey("identity.Clinic", on_delete=models.PROTECT)
    resource = models.ForeignKey(ScimResource, on_delete=models.PROTECT)
    membership = models.ForeignKey("identity.UserClinicRole", on_delete=models.PROTECT)
    manages_membership = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    revoked_at = models.DateTimeField(null=True)

    class Meta:
        """Keep revoked associations while permitting only one current binding."""

        constraints: ClassVar = [
            models.UniqueConstraint(
                fields=("membership",),
                condition=models.Q(revoked_at__isnull=True),
                name="identity_scim_binding_current",
            ),
        ]
